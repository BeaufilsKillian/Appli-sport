const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { load, device } = require('./sync.cjs');
const initSqlJs = require('sql.js');
const d = load('src/db.ts');
const { parseBackup } = load('src/backup.ts');
const { backupFingerprint } = load('src/web/backupFingerprint.ts');
const { createSetWriter } = load('src/setEditing.ts');
const { previousPerformance, parseSetDuration, formatSetDuration } = load('src/setInputs.ts');
const { workoutProgress } = load('src/workoutProgress.ts');
const { rmReview } = load('src/rmReview.ts');
const sharing = load('src/folderSharing.ts');
(async () => {
  for (const [text, expected] of [['90',90],['1:30',90],['20:00',1200],['1440:00',86400],['1:',null],['1:60',null],['-1',null],['1.5',null],['86401',null],['',null]]) assert.equal(parseSetDuration(text), expected, text);
  assert.equal(formatSetDuration(1200), '20:00');
  assert.equal(d.suggestedLoad(100,8,2),75);
  assert.equal(d.suggestedLoad(100,8,0),80);
  assert(d.suggestedLoad(100,15,3) < d.suggestedLoad(100,15,0));
  assert.equal(d.suggestedLoad(100,15,-1),0);

  const engine = await initSqlJs(), source = await device(engine), receiver = await device(engine);
  const db = source.db;
  const folder = await d.createFolder(db,'Durées');
  const templateId = await d.createTemplate(db,'Mixte',folder);
  for (const id of ['bench','plank']) await d.addExercise(db,templateId,id);
  await d.changeExercisePlan(db,templateId,'bench',3,12,120,false,15,0,false,'',15,12);
  await d.changeExercisePlan(db,templateId,'plank',2,0,30,false,15,0,false,'',null,null,60);
  await d.saveExerciseMax(db,'bench',100,3);
  let reference = (await d.fetchOverview(db)).exerciseMaxes[0];
  await db.runAsync('UPDATE exercise_maxes SET updated_at=123 WHERE exercise_id=?','bench');
  await d.saveExerciseMax(db,'bench',100,4);
  assert.equal((await d.fetchOverview(db)).exerciseMaxes[0].updated_at,123,'la réserve seule ne renouvelle pas le RM');
  await d.saveExerciseMax(db,'bench',100,3,true);
  reference = (await d.fetchOverview(db)).exerciseMaxes[0]; assert(reference.updated_at > 123);
  await assert.rejects(d.saveExerciseMax(db,'bench',100,11),/réserve/);
  await assert.rejects(d.changeExercisePlan(db,templateId,'plank',2,0,30,false,15,0,false,'',null,null,86401),/Durée/);
  let overview = await d.fetchOverview(db);
  const template = overview.templates[0];
  const workout = await d.startSelectedSession(db,template,overview.templateExercises,overview.exerciseMaxes);
  assert.equal(workout.sets.find(set=>set.exercise_id==='bench').weight,d.suggestedLoad(100,15,3));
  const timed = workout.sets.filter(set=>set.exercise_id==='plank');
  assert.equal(timed[0].reps,0); assert.equal(timed[0].duration_seconds,0);
  assert.equal(workout.sessionExercises.find(plan=>plan.exercise_id==='plank').planned_duration_seconds,60);
  let saved; const writer = createSetWriter(db,set=>{saved=set;});
  await writer.write(timed[0].id,{field:'duration',text:'1:'}); assert.equal(saved.completed,0);
  await source.reopen();
  assert.equal((await d.fetchOverview(source.db)).activeSets.find(set=>set.id===timed[0].id).input.duration,'1:','brouillon conservé après réouverture');
  const resumedWriter = createSetWriter(source.db,set=>{saved=set;});
  await resumedWriter.write(timed[0].id,{field:'duration',text:'1:30'});
  assert.equal(saved.completed,1); assert.equal(saved.duration_seconds,90); assert.equal(saved.weight,0,'charge facultative'); assert.equal(saved.reps,0);
  await resumedWriter.write(timed[0].id,'toggle'); assert.equal(saved.completed,0);
  await resumedWriter.write(timed[0].id,'toggle'); assert.equal(saved.completed,1);
  await resumedWriter.write(timed[1].id,{field:'duration',text:'0:45'}); assert.equal(saved.duration_seconds,45);
  const extra = await d.createLoggedSet(source.db,workout.session.id,'plank',saved); assert.equal(extra.duration_seconds,0);
  await d.deleteLoggedSet(source.db,extra.id);
  await d.changeExercisePlan(source.db,templateId,'plank',2,12,30,false,15,0,false,'',15,12);
  assert.equal((await d.fetchOverview(source.db)).activeSessionExercises.find(plan=>plan.exercise_id==='plank').planned_duration_seconds,60,'séance active indépendante du modèle modifié');
  await d.finishSession(source.db,workout.session.id);
  const hist = (await d.fetchOverview(source.db)).historySets;
  const historyTimed = hist.find(set=>set.id===timed[0].id);
  assert.equal(previousPerformance(hist,{...historyTimed,duration_seconds:null}),null,'ne pas copier une durée dans les répétitions');
  assert.equal(previousPerformance(hist,historyTimed).duration_seconds,90);

  const snapshot = parseBackup(await d.exportAllData(source.db));
  assert.equal(snapshot.schema,11); assert.equal(snapshot.logged_sets.find(set=>set.id===timed[0].id).duration_seconds,90);
  await receiver.db.restore(snapshot); await receiver.reopen();
  assert.equal((await d.fetchOverview(receiver.db)).historySets.find(set=>set.id===timed[0].id).duration_seconds,90);
  assert.equal((await d.fetchOverview(receiver.db)).exerciseMaxes[0].reserve_reps,3);
  const bad = structuredClone(snapshot); bad.logged_sets.find(set=>set.id===timed[0].id).reps=90;
  assert.throws(()=>parseBackup(bad),/Durée/);
  const invalidReserve = structuredClone(snapshot); invalidReserve.exercise_maxes[0].reserve_reps=11;
  assert.throws(()=>parseBackup(invalidReserve),/Réserve/);

  await d.changeExercisePlan(source.db,templateId,'plank',1,0,0,false,15,0,false,'Tapis ou gainage',null,null,1200);
  const shared = sharing.makeSharedFolder(parseBackup(await d.exportAllData(source.db)),folder);
  assert.equal(shared.version,2);
  const importedId = await sharing.importSharedFolder(receiver.db,shared,crypto.randomUUID());
  const importedTemplate = (await d.fetchOverview(receiver.db)).templates.find(t=>t.folder_id===importedId);
  assert.equal((await d.fetchOverview(receiver.db)).templateExercises.find(plan=>plan.template_id===importedTemplate.id&&plan.exercise_id==='plank').planned_duration_seconds,1200);

  const legacy = structuredClone(snapshot); legacy.schema=9;
  for(const row of legacy.template_exercises) delete row.planned_duration_seconds;
  for(const row of legacy.session_exercises) delete row.planned_duration_seconds;
  for(const row of legacy.logged_sets) delete row.duration_seconds;
  for(const row of legacy.exercise_maxes) delete row.reserve_reps;
  const upgraded = parseBackup(legacy);
  assert(upgraded.logged_sets.every(set=>set.duration_seconds===null)); assert.equal(upgraded.exercise_maxes[0].reserve_reps,2);
  const same = structuredClone(upgraded);
  const oldContent = Object.fromEntries(Object.keys(load('src/backup.ts').BACKUP_TABLES).map(table=>[table,(table==='settings'?same[table].filter(row=>!load('src/web/backupFingerprint.ts').isImplicitSetting(row)):same[table]).map(row=>{
    const copy={...row}; delete copy.planned_duration_seconds; delete copy.duration_seconds; delete copy.reserve_reps;delete copy.load_step;delete copy.progression_key;delete copy.suggested_load;delete copy.progression_reason;
    return JSON.stringify(copy);
  }).sort()]));
  assert.equal(await backupFingerprint(same),crypto.createHash('sha256').update(JSON.stringify(oldContent)).digest('hex'),'migration sans faux conflit de synchronisation');
  same.exercise_maxes[0].reserve_reps=4; assert.notEqual(await backupFingerprint(same),await backupFingerprint(upgraded));
  const legacyShared = {...shared,version:1,template_exercises:shared.template_exercises.map(plan=>({...plan,planned_duration_seconds:undefined,planned_reps:12,planned_reps_min:12,planned_reps_max:15}))};
  assert(sharing.parseSharedFolder(legacyShared).template_exercises.every(plan=>plan.planned_duration_seconds===null));
  const plans=[{exercise_id:'plank',position:0,superset_group:0,rest_seconds:0,target_reps:0,planned_duration_seconds:1200},{exercise_id:'bench',position:1,superset_group:0,rest_seconds:0,target_reps:15}];
  assert.equal(workoutProgress(plans,[{exercise_id:'plank',ordinal:1,set_kind:'normal',duration_seconds:1200,completed:1},{exercise_id:'bench',ordinal:1,set_kind:'normal',completed:0}]),1200/1260,'pondération selon les vraies secondes prévues');

  const now=Date.now(), ref={exercise_id:'bench',weight:100,updated_at:now-86400000,reserve_reps:2};
  const performances=[1,2,3].map((id)=>({session_id:String(id),exercise_id:'bench',started_at:now-1000,finished_at:now-500+id,completed:1,weight:80,reps:15,rpe:10,set_kind:'normal',duration_seconds:null}));
  assert.match(rmReview(ref,performances,now),/plus élevé/,'15 répétitions à l’échec acceptées');
  assert.match(rmReview(ref,performances.map(s=>({...s,rpe:8,weight:75})),now),/plus élevé/,'12–15 avec réserve renseignée');
  assert.equal(rmReview(ref,performances.slice(0,2),now),null);
  assert.equal(rmReview(ref,performances.map(s=>({...s,rpe:null})),now),null,'pas de déduction sans difficulté');
  assert.equal(rmReview(ref,performances.map((s,i)=>({...s,rpe:10-i})),now),null,'ne pas mélanger les difficultés');
  assert.equal(rmReview(ref,performances.map(s=>({...s,set_kind:'drop'})),now),null);
  assert.equal(rmReview(ref,performances.map(s=>({...s,duration_seconds:60})),now),null);
  assert.equal(rmReview(ref,performances.map(s=>({...s,reps:16})),now),null);
  assert.match(rmReview(ref,performances.map(s=>({...s,weight:50})),now),/plus bas/);
  assert.match(rmReview({...ref,updated_at:now-42*86400000},[],now),/6 semaines/);
  assert.equal(rmReview({...ref,weight:0},performances,now),null);

  // Migration réelle d'une base précédente avec une séance et un brouillon actifs.
  const oldDevice = await device(engine);
  const oldFolder = await d.createFolder(oldDevice.db,'Ancien appareil');
  const oldTemplateId = await d.createTemplate(oldDevice.db,'En cours',oldFolder);
  await d.addExercise(oldDevice.db,oldTemplateId,'bench'); await d.saveExerciseMax(oldDevice.db,'bench',100);
  const oldOverview = await d.fetchOverview(oldDevice.db);
  const oldWorkout = await d.startSelectedSession(oldDevice.db,oldOverview.templates[0],oldOverview.templateExercises,oldOverview.exerciseMaxes);
  await createSetWriter(oldDevice.db,()=>{}).write(oldWorkout.sets[0].id,{field:'weight',text:'25'});
  await oldDevice.db.execAsync('UPDATE session_exercises SET progression_key=NULL,suggested_load=NULL,progression_reason=NULL');
  const oldFingerprint = await backupFingerprint((await oldDevice.db.snapshot()).data);
  await oldDevice.db.withExclusiveTransactionAsync(async tx=>{
    for(const [table,column] of [['template_exercises','planned_duration_seconds'],['session_exercises','planned_duration_seconds'],['logged_sets','duration_seconds'],['exercise_maxes','reserve_reps'],['exercise_maxes','load_step'],['session_exercises','progression_key'],['session_exercises','suggested_load'],['session_exercises','progression_reason']]) await tx.execAsync(`ALTER TABLE ${table} DROP COLUMN ${column}`);
  });
  await oldDevice.reopen();
  const migrated = await d.fetchOverview(oldDevice.db);
  assert.equal(migrated.active.id,oldWorkout.session.id); assert.equal(migrated.activeSets[0].input.weight,'25'); assert.equal(migrated.activeSets[0].input.reps,''); assert.equal(migrated.activeSets[0].completed,0);
  assert.equal(migrated.activeSets[0].duration_seconds,null); assert.equal(migrated.exerciseMaxes[0].reserve_reps,2);
  assert.equal(await backupFingerprint((await oldDevice.db.snapshot()).data),oldFingerprint);
  await oldDevice.db.close();

  // Même nouveau format à travers le transport de synchronisation des deux appareils.
  const remoteDevice = await device(engine);
  const {synchronize} = load('src/web/synchronize.ts');
  let cloud=null;
  const transport={get:async()=>({latest:structuredClone(cloud),versions:cloud?[{revision:cloud.revision,created_at:cloud.created_at}]:[]}),save:async(base,data)=>{assert.equal(base,cloud?.revision??0);cloud={revision:base+1,payload:parseBackup(data),created_at:new Date().toISOString()};return {revision:cloud.revision};}};
  await synchronize(source.db,transport,()=>true);
  await synchronize(remoteDevice.db,transport,()=>true);
  assert.equal((await d.fetchOverview(remoteDevice.db)).historySets.find(set=>set.id===timed[0].id).duration_seconds,90);
  await d.saveExerciseMax(remoteDevice.db,'bench',100,1);
  await synchronize(remoteDevice.db,transport,()=>true);
  await synchronize(source.db,transport,()=>true);
  assert.equal((await d.fetchOverview(source.db)).exerciseMaxes[0].reserve_reps,1);
  await remoteDevice.db.close();
  await source.db.close(); await receiver.db.close();
  console.log('OK - durées, brouillons, unités, historique, migration, sauvegardes, partage, progression, Epley/RIR et rappels RM.');
})().catch(error=>{console.error(error);process.exitCode=1;});
