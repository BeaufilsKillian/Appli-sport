const assert = require('node:assert/strict');
const { load, device } = require('./sync.cjs');
const initSqlJs = require('sql.js');
const d = load('src/db.ts');
const { confirmedMax } = load('src/confirmedMax.ts');
const sets = [1,2,3].map(ordinal => ({ordinal,weight:170,reps:12,completed:1,set_kind:'normal',duration_seconds:null}));
assert.equal(confirmedMax(sets,3,180),238);
assert.equal(confirmedMax(sets.slice(0,1),1,180),null);
assert.equal(confirmedMax(sets.slice(0,2),3,180),null);
assert.equal(confirmedMax(sets.map((s,i)=>({...s,weight:i?100:170})),3,180),null);
assert.equal(confirmedMax(sets.map((s,i)=>({...s,weight:i?170:700})),3,180),null);
assert.equal(confirmedMax(sets.map((s,i)=>({...s,completed:i?1:0})),3,180),null);
assert.equal(confirmedMax(sets.map(s=>({...s,duration_seconds:60})),3,180),null);
assert.equal(confirmedMax(sets,3,250),null);
assert.equal(confirmedMax([...sets,{...sets[0],set_kind:'drop',weight:10}],3,180),238);
assert.equal(confirmedMax(sets.map(s=>({...s,reps:16})),3,180),null);
assert.equal(confirmedMax(sets.map(s=>({...s,reps:1,weight:190})),3,180),190);
(async()=>{
  const source = await device(await initSqlJs());
  const db=source.db, folder=await d.createFolder(db,'RM'), template=await d.createTemplate(db,'Test RM',folder);
  await d.addExercise(db,template,'bench');
  await d.changeExercisePlan(db,template,'bench',3,12,120,false,15,0,false,'',15,12);
  await d.saveExerciseMax(db,'bench',180);
  const start=async()=>{const o=await d.fetchOverview(db);return d.startSelectedSession(db,o.templates[0],o.templateExercises,o.exerciseMaxes);};
  let workout=await start();
  for(const set of workout.sets)await d.updateLoggedSet(db,{...set,weight:170,reps:12,completed:1});
  assert.equal((await d.fetchOverview(db)).exerciseMaxes[0].weight,180,'attendre la fin de séance');
  await d.finishSession(db,workout.session.id);
  assert.equal((await d.fetchOverview(db)).exerciseMaxes[0].weight,238);
  await d.finishSession(db,workout.session.id);
  assert.equal((await d.fetchOverview(db)).exerciseMaxes[0].weight,238,'fin idempotente');
  workout=await start();
  const before=await d.fetchOverview(db);
  await d.saveExerciseMax(db,'bench',250,3);
  let after=await d.fetchOverview(db);
  assert.equal(after.activeSessionExercises[0].suggested_load,d.suggestedLoad(250,15,3));
  assert.deepEqual(after.activeSets,before.activeSets,'aucune performance ni brouillon réécrit');
  await source.reopen();
  after=await d.fetchOverview(source.db);
  assert.equal(after.activeSessionExercises[0].suggested_load,d.suggestedLoad(250,15,3),'suggestion conservée après réouverture');
  await d.discardSession(source.db,workout.session.id);
  await d.saveExerciseMax(source.db,'bench',300,3);
  const o=await d.fetchOverview(source.db);
  workout=await d.startSelectedSession(source.db,o.templates[0],o.templateExercises,o.exerciseMaxes);
  assert.equal(workout.sessionExercises[0].suggested_load,d.suggestedLoad(300,15,3),'un nouveau RM remplace les anciennes suggestions');
  await source.db.close();
  console.log('OK RM confirmé : hausse multi-séries, fautes de frappe, saisies conservées, recalcul immédiat et persistant.');
})().catch(error=>{console.error(error);process.exitCode=1;});
